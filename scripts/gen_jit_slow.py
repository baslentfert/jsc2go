# Generates vm/jit_slow_gen.go: the slow paths of the instructions of
# VM.run (vm/interpreter.go) that generated code does not compile, copied
# from their cases in VM.run so that they stay the same (JSC's baseline
# JIT calls a slow_path_* operation for every opcode it has no inline code
# for, DEFINE_SLOW_OP). Run from the repository root:
#
#	python scripts/gen_jit_slow.py
import re
import subprocess

# The instructions of VM.run to copy (switches return their target).
OPS = '''ArgumentCount ConstructVarargs CreateGeneratorFrameEnvironment CreatePromise CreateRest
DefineDataProperty EnumeratorGetByVal EnumeratorHasOwnProperty EnumeratorInByVal EnumeratorNext
GetArgument GetByIdDirect GetPrivateName GetPropertyEnumerator GetScope InById InByVal IsCallable
IsEmpty IsUndefinedOrNull IteratorNext IteratorOpen NewArrayBuffer NewArrayWithSize NewAsyncFunc
NewAsyncFuncExp NewAsyncGeneratorFunc NewAsyncGeneratorFuncExp NewGeneratorFunc NewGeneratorFuncExp
PutByValDirect PutPrivateName ToObject SwitchImm SwitchChar SwitchString'''.split()
WANT = {'Op%sID' % o for o in OPS}

src = open('vm/interpreter.go', encoding='utf-8').read().replace('\r', '')
start = src.index('func (vm *VM) run(f *Frame) Value {')
end = src.index('\t\tdefault:\n\t\t\tvm.runCold(f, op, in)', start)
body = src[src.index('\t\tswitch op {\n', start) + len('\t\tswitch op {\n'):end]

# Split into case clauses at two tabs of indentation.
clauses, cur = [], []
for line in body.split('\n'):
    if line.startswith('\t\tcase '):
        if cur:
            clauses.append(cur)
        cur = [line]
    elif cur:
        cur.append(line)
if cur:
    clauses.append(cur)

out, found = [], set()
for cl in clauses:
    labels = set(re.findall(r'bytecode\.(Op\w+ID)', cl[0]))
    if not labels & WANT:
        continue
    # A case may share its body with instructions that generated code
    # compiles itself (new_func with the generator kinds): those never get
    # here.
    found |= labels
    # Drop the trailing blank and section comment lines.
    while cl and (cl[-1].strip() == '' or cl[-1].strip().startswith('//')):
        cl.pop()
    text = '\n'.join(l[1:] if l.startswith('\t') else l for l in cl)
    # (a return inside a function literal on its line is the literal's)
    loop = '\n'.join(re.sub(r'func\(.*?\{.*\}', '', l) for l in text.split('\n'))
    if re.search(r'\bins\b|\breturn\b|\bcontinue\b|f\.pc\b', loop):
        raise SystemExit('case %s uses state of the interpreter loop' % cl[0])
    out.append(text)
missing = WANT - found
if missing:
    raise SystemExit('not found in VM.run: %s' % sorted(missing))

go = '''// Code generated by scripts/gen_jit_slow.py from VM.run; DO NOT EDIT.

//go:build ((arm64 || amd64) && (darwin || linux)) || (amd64 && windows)

package vm

import "github.com/baslentfert/jsc2go/bytecode"

// jitGenericOps are the instructions of VM.run whose slow path is
// jitSlowGeneric.
var jitGenericOps = func() (set [bytecode.NumberOfBytecodeIDs]bool) {
	for _, op := range []bytecode.OpcodeID{
%s
	} {
		set[op] = true
	}
	return
}()

// jitSlowGeneric runs one of jitGenericOps as VM.run does and returns the
// pc to continue at.
func (vm *VM) jitSlowGeneric(f *Frame, pc int, in []uint32, op bytecode.OpcodeID) int {
	cb := f.cb
	r := cb.realm
	_ = r
	next := pc + op.Length()
	switch op {
%s
	}
	return next
}
''' % ('\n'.join('\t\tbytecode.%s,' % o for o in sorted(WANT)), '\n'.join(out))
open('vm/jit_slow_gen.go', 'w', encoding='utf-8', newline='\n').write(go)
subprocess.run(['gofmt', '-w', 'vm/jit_slow_gen.go'], check=True)
print('%d instructions' % len(found))
